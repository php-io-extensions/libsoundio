<?php

declare(strict_types=1);

/*
 * Writes stubs/soundio_constants.stub.php from soundio.h: every enumerator of every enum, the
 * native/foreign-endian format aliases, and SOUNDIO_MAX_CHANNELS, each registered with @cvalue so
 * the value is the header's.
 *
 *   php84 tools/constants.php [path/to/soundio.h]
 */

$header = $argv[1] ?? '/opt/homebrew/include/soundio/soundio.h';
$source = file_get_contents($header);
if ($source === false) {
    fwrite(STDERR, "cannot read {$header}\n");
    exit(1);
}

$names = [];
preg_match_all('/^enum (SoundIo\w+) \{(.*?)^\};/ms', $source, $enums, PREG_SET_ORDER);
foreach ($enums as [, $enum, $body]) {
    $body = preg_replace('#///[^\n]*#', '', $body);
    preg_match_all('/^\s*(SoundIo\w+)\s*(?:=[^,\n]*)?,?/m', $body, $m);
    $names[$enum] = $m[1];
}

preg_match_all('/^#define (SoundIoFormat\w+[NF]E)\b/m', $source, $aliases);
$names['endian aliases'] = array_values(array_unique($aliases[1]));
$names['limits'] = ['SOUNDIO_MAX_CHANNELS'];

$out = "<?php\n\n/** @generate-class-entries */\n\n/* Generated by tools/constants.php from soundio.h. Do not edit; rerun the tool. */\n";
foreach ($names as $group => $list) {
    $out .= "\n/* {$group} */\n";
    foreach ($list as $name) {
        $out .= "\n/**\n * @var int\n * @cvalue {$name}\n */\nconst {$name} = UNKNOWN;\n";
    }
}

file_put_contents(__DIR__ . '/../stubs/soundio_constants.stub.php', $out);
printf("%d constants\n", array_sum(array_map('count', $names)));
